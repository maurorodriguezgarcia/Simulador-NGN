// Accurate projection onto Colombia map viewBox 0 0 360 440
// Lon range: -79.2 to -66.8, Lat range: 12.6 to -4.3
export function projectColombiaCoords(lat: number, lon: number): { mapX: number; mapY: number } {
  const minLon = -79.4;
  const maxLon = -66.5;
  const maxLat = 13.0;
  const minLat = -4.6;
  const x = ((lon - minLon) / (maxLon - minLon)) * 320 + 20;
  const y = ((maxLat - lat) / (maxLat - minLat)) * 400 + 20;
  return { mapX: Math.round(x), mapY: Math.round(y) };
}

